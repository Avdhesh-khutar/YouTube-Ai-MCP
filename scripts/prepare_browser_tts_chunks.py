#!/usr/bin/env python3
"""Split a Hindi narration into browser-TTS-sized, sentence-preserving chunks.

This helper does not call a TTS provider. It prepares numbered text files for a
browser demo and a manifest so downloaded WAV files can be matched and assembled.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

SENTENCE_END = re.compile(r"(?<=[।!?])\s+|\n+")


def split_long_sentence(sentence: str, limit: int) -> list[str]:
    words = sentence.split()
    parts: list[str] = []
    current = ""
    for word in words:
        if len(word) > limit:
            raise ValueError(f"Single token exceeds chunk limit ({limit} characters).")
        candidate = f"{current} {word}".strip()
        if len(candidate) <= limit:
            current = candidate
        else:
            if current:
                parts.append(current)
            current = word
    if current:
        parts.append(current)
    return parts


def chunk_text(text: str, limit: int = 1800) -> list[str]:
    if limit < 100:
        raise ValueError("Chunk limit must be at least 100 characters.")
    normalized = re.sub(r"[ \t]+", " ", text.replace("\r\n", "\n")).strip()
    if not normalized:
        raise ValueError("Narration text is empty.")
    sentences = [s.strip() for s in SENTENCE_END.split(normalized) if s.strip()]
    chunks: list[str] = []
    current = ""
    for sentence in sentences:
        pieces = split_long_sentence(sentence, limit)
        for piece in pieces:
            candidate = f"{current} {piece}".strip()
            if len(candidate) <= limit:
                current = candidate
            else:
                if current:
                    chunks.append(current)
                current = piece
    if current:
        chunks.append(current)
    return chunks


def prepare(source: Path, output: Path, limit: int = 1800) -> Path:
    raw = source.read_text(encoding="utf-8")
    chunks = chunk_text(raw, limit)
    output.mkdir(parents=True, exist_ok=True)
    rows = []
    for index, chunk in enumerate(chunks, 1):
        filename = f"chunk-{index:03d}.txt"
        (output / filename).write_text(chunk + "\n", encoding="utf-8")
        rows.append({
            "index": index,
            "file": filename,
            "characters": len(chunk),
            "sha256": hashlib.sha256(chunk.encode("utf-8")).hexdigest(),
            "status": "awaiting_browser_tts",
            "expected_audio_file": f"chunk-{index:03d}.wav",
        })
    manifest = {
        "language": "hi-IN",
        "provider": "browser_manual",
        "max_characters_per_chunk": limit,
        "chunk_count": len(rows),
        "chunks": rows,
        "assembly_instruction": "Generate each text file in the selected browser TTS tool; save its WAV output using expected_audio_file. Then assemble the numbered WAV files with FFmpeg after listening to every chunk.",
        "status": "text_chunks_prepared_audio_not_generated",
    }
    path = output / "tts-chunks-manifest.json"
    path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True, help="UTF-8 Hindi narration text")
    parser.add_argument("--output", type=Path, required=True, help="Directory for numbered text chunks")
    parser.add_argument("--max-characters", type=int, default=1800)
    args = parser.parse_args()
    manifest = prepare(args.input, args.output, args.max_characters)
    print(f"TTS text chunks prepared: {manifest}")
    print("Audio is not generated by this script; use a browser TTS provider and review each WAV.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
